-- Minimal schema for SessionRepository integration tests.
-- Authoritative DDL: docs/detailed-design/02-data/mysql-tables.md §6.2

CREATE TABLE sessions (
  id                              BIGINT(20)   NOT NULL COMMENT '主键 SFID',
  tenant                          INT(10)      NOT NULL COMMENT '租户',
  user_id                         VARCHAR(64)  NOT NULL COMMENT 'UserPrincipal.userId',
  agent_id                        BIGINT(20)   NOT NULL COMMENT '引用 descriptors.id（无 FK）',
  agent_version_no                INT          NOT NULL COMMENT '冻结的 Agent 版本号',
  agent_snapshot_json             JSON         NOT NULL COMMENT 'Agent 快照',
  user_principal_snapshot_json    JSON         NOT NULL COMMENT 'UserPrincipal 快照',
  title                           VARCHAR(255) NULL,
  status                          VARCHAR(32)  NOT NULL DEFAULT 'ACTIVE',
  last_turn_id                    BIGINT(20)  NULL,
  last_active_time                DATETIME(3)  NOT NULL,
  context_json                    JSON         NULL,
  deleted                         BIGINT(20)   NOT NULL DEFAULT 0,
  create_by                       VARCHAR(64)  NOT NULL,
  creator_id                      VARCHAR(64)  NULL,
  creator_type                    VARCHAR(16)  NULL,
  create_time                     DATETIME(3)  NOT NULL,
  update_by                       VARCHAR(64)  NOT NULL,
  updater_id                      VARCHAR(64)  NULL,
  updater_type                    VARCHAR(16)  NULL,
  update_time                     DATETIME(3)  NOT NULL,
  PRIMARY KEY (id),
  KEY idx_tenant_deleted (tenant, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='sessions (test fixture)';

