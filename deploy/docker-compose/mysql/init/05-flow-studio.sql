-- Flow Studio — replicated ai-application flow-editor projection layer (ADR-0014).
-- Tables renamed ai_application_flow_* -> flow_studio_* and `tenant` INT -> `tenant_id` VARCHAR(64)
-- to align with the cube-ai-project identity model (tenantContextAls.tenantId: string).
-- Lives in the same database as flow-core (agentic_engine). MySQL only (ADR-0013, no SQLite).
USE agentic_engine;

CREATE TABLE IF NOT EXISTS `flow_studio_flow` (
    `id` BIGINT NOT NULL COMMENT '主键ID',
    `tenant_id` VARCHAR(64) NOT NULL COMMENT '租户编号',
    `name` VARCHAR(255) NOT NULL COMMENT '流程名称',
    `description` VARCHAR(512) DEFAULT NULL COMMENT '流程描述',
    `editor_flow_json` LONGTEXT NOT NULL COMMENT '编辑态流程JSON',
    `compiled_flow_json` LONGTEXT DEFAULT NULL COMMENT '编译态流程JSON',
    `component_snapshot_json` LONGTEXT DEFAULT NULL COMMENT '组件快照JSON',
    `compile_status` VARCHAR(64) NOT NULL DEFAULT 'draft' COMMENT '编译状态',
    `compile_error` VARCHAR(1024) DEFAULT NULL COMMENT '编译错误',
    `compile_revision` BIGINT NOT NULL DEFAULT 0 COMMENT '编译版本号',
    `remote_flow_id` VARCHAR(128) DEFAULT NULL COMMENT '远端 flow-core 流程ID',
    `remote_binding_status` VARCHAR(64) DEFAULT NULL COMMENT '远端绑定状态',
    `published_release_id` BIGINT DEFAULT NULL COMMENT '当前已发布版本ID',
    `published_revision` BIGINT DEFAULT NULL COMMENT '当前已发布编译版本号',
    `last_compiled_time` DATETIME DEFAULT NULL COMMENT '最近编译时间',
    `last_synced_time` DATETIME DEFAULT NULL COMMENT '最近同步远端时间',
    `enabled` TINYINT(1) DEFAULT 1 COMMENT '是否启用',
    `remark` VARCHAR(512) DEFAULT NULL COMMENT '备注',
    `create_by` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '创建用户',
    `creator_id` VARCHAR(100) DEFAULT NULL COMMENT '创建用户id',
    `creator_type` VARCHAR(50) DEFAULT NULL COMMENT '创建用户类型',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '更新用户',
    `updater_id` VARCHAR(100) DEFAULT NULL COMMENT '更新用户id',
    `updater_type` VARCHAR(50) DEFAULT NULL COMMENT '更新用户类型',
    `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` BIGINT(20) DEFAULT 0 COMMENT '是否删除：0-否，>0-逻辑删除版本',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_flow_studio_flow_name_tenant_deleted` (`tenant_id`, `name`, `deleted`),
    UNIQUE KEY `uk_flow_studio_flow_remote_deleted` (`remote_flow_id`, `deleted`),
    KEY `idx_flow_studio_flow_tenant_status_deleted` (`tenant_id`, `compile_status`, `deleted`),
    KEY `idx_flow_studio_flow_tenant_update_deleted` (`tenant_id`, `update_time`, `deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='Flow Studio 流程表';

CREATE TABLE IF NOT EXISTS `flow_studio_resource_ref` (
    `id` BIGINT NOT NULL COMMENT '主键ID',
    `tenant_id` VARCHAR(64) NOT NULL COMMENT '租户编号',
    `flow_id` BIGINT NOT NULL COMMENT '流程ID',
    `node_id` VARCHAR(128) NOT NULL COMMENT '节点ID',
    `component_key` VARCHAR(128) NOT NULL COMMENT '组件Key',
    `resource_type` VARCHAR(64) NOT NULL COMMENT '资源类型',
    `resource_id` VARCHAR(128) NOT NULL COMMENT '资源ID',
    `resource_sub_id` VARCHAR(128) DEFAULT NULL COMMENT '子资源ID',
    `resource_name_snapshot` VARCHAR(255) DEFAULT NULL COMMENT '资源名称快照',
    `resource_status_snapshot` VARCHAR(64) DEFAULT NULL COMMENT '资源状态快照',
    `required` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否强依赖',
    `invalid` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否已失效',
    `invalid_reason` VARCHAR(512) DEFAULT NULL COMMENT '失效原因',
    `remark` VARCHAR(512) DEFAULT NULL COMMENT '备注',
    `create_by` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '创建用户',
    `creator_id` VARCHAR(100) DEFAULT NULL COMMENT '创建用户id',
    `creator_type` VARCHAR(50) DEFAULT NULL COMMENT '创建用户类型',
    `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '更新用户',
    `updater_id` VARCHAR(100) DEFAULT NULL COMMENT '更新用户id',
    `updater_type` VARCHAR(50) DEFAULT NULL COMMENT '更新用户类型',
    `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` BIGINT(20) DEFAULT 0 COMMENT '是否删除：0-否，>0-逻辑删除版本',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_flow_studio_ref_unique_deleted` (`flow_id`, `node_id`, `resource_type`, `resource_id`, `deleted`),
    KEY `idx_flow_studio_ref_tenant_flow_deleted` (`tenant_id`, `flow_id`, `deleted`),
    KEY `idx_flow_studio_ref_resource_deleted` (`tenant_id`, `resource_type`, `resource_id`, `deleted`),
    KEY `idx_flow_studio_ref_invalid_deleted` (`tenant_id`, `invalid`, `deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='Flow Studio 流程资源引用表';

