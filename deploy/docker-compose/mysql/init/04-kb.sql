USE cube_ai_center;

CREATE TABLE IF NOT EXISTS `document_directory_record` (
  `id` VARCHAR(64) NOT NULL,
  `tenant_id` VARCHAR(64) NULL,
  `deleted` BIGINT NULL,
  `create_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `creator_id` VARCHAR(64) NULL,
  `creator_type` VARCHAR(64) NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `updater_id` VARCHAR(64) NULL,
  `updater_type` VARCHAR(64) NULL,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `name` VARCHAR(255) NOT NULL,
  `description` TEXT NULL,
  `icon` VARCHAR(512) NULL,
  PRIMARY KEY (`id`),
  KEY `idx_document_directory_tenant` (`tenant_id`),
  KEY `idx_document_directory_deleted` (`deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `document_record` (
  `id` VARCHAR(64) NOT NULL,
  `tenant_id` VARCHAR(64) NULL,
  `deleted` BIGINT NULL,
  `create_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `creator_id` VARCHAR(64) NULL,
  `creator_type` VARCHAR(64) NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `updater_id` VARCHAR(64) NULL,
  `updater_type` VARCHAR(64) NULL,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `name` VARCHAR(512) NOT NULL,
  `mime_type` VARCHAR(128) NOT NULL,
  `extension` VARCHAR(32) NOT NULL,
  `size` BIGINT NOT NULL DEFAULT 0,
  `storage_bucket` VARCHAR(255) NOT NULL,
  `storage_key` VARCHAR(1024) NOT NULL,
  `directory_id` VARCHAR(64) NULL,
  `status` VARCHAR(32) NOT NULL,
  `parse_status` VARCHAR(32) NOT NULL,
  `index_status` VARCHAR(32) NOT NULL,
  `error_message` TEXT NULL,
  `recall_count` INT NOT NULL DEFAULT 0,
  `char_count` INT NOT NULL DEFAULT 0,
  `chunk_separator` VARCHAR(64) NULL,
  `chunk_size` INT NULL,
  `chunk_overlap` INT NULL,
  `table_chunk_mode` VARCHAR(64) NULL,
  `text_chunk_mode` VARCHAR(64) NULL,
  PRIMARY KEY (`id`),
  KEY `idx_document_record_directory` (`directory_id`),
  KEY `idx_document_record_tenant` (`tenant_id`),
  KEY `idx_document_record_deleted` (`deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `document_import_job` (
  `id` VARCHAR(64) NOT NULL,
  `tenant_id` VARCHAR(64) NULL,
  `deleted` BIGINT NULL,
  `create_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `creator_id` VARCHAR(64) NULL,
  `creator_type` VARCHAR(64) NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `updater_id` VARCHAR(64) NULL,
  `updater_type` VARCHAR(64) NULL,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `document_id` VARCHAR(64) NOT NULL,
  `status` VARCHAR(32) NOT NULL,
  `error_message` TEXT NULL,
  `chunk_count` INT NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_import_job_document` (`document_id`),
  KEY `idx_import_job_tenant` (`tenant_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `document_chunk` (
  `id` VARCHAR(64) NOT NULL,
  `tenant_id` VARCHAR(64) NULL,
  `deleted` BIGINT NULL,
  `create_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `creator_id` VARCHAR(64) NULL,
  `creator_type` VARCHAR(64) NULL,
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_by` VARCHAR(64) NOT NULL DEFAULT 'system',
  `updater_id` VARCHAR(64) NULL,
  `updater_type` VARCHAR(64) NULL,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `document_id` VARCHAR(64) NOT NULL,
  `file_name` VARCHAR(512) NOT NULL,
  `source_type` VARCHAR(64) NOT NULL,
  `chunk_id` VARCHAR(128) NOT NULL,
  `qdrant_point_id` CHAR(36) NOT NULL,
  `chunk_index` INT NOT NULL,
  `text_content` MEDIUMTEXT NOT NULL,
  `embedding_text` MEDIUMTEXT NOT NULL,
  `char_count` INT NOT NULL DEFAULT 0,
  `recall_count` INT NOT NULL DEFAULT 0,
  `section_id` VARCHAR(256) NOT NULL,
  `heading_path` TEXT NOT NULL,
  `page_no` INT NULL,
  `chunk_type` VARCHAR(64) NOT NULL,
  `order_in_section` INT NOT NULL DEFAULT 0,
  `caption_text` TEXT NULL,
  `picture_description` TEXT NULL,
  `sheet_name` VARCHAR(256) NULL,
  `table_id` VARCHAR(256) NULL,
  `row_start` INT NULL,
  `row_end` INT NULL,
  `headers_text` TEXT NULL,
  `keywords_text` TEXT NULL,
  `start_time` VARCHAR(64) NULL,
  `end_time` VARCHAR(64) NULL,
  `cue_index` INT NULL,
  `property_namespace` VARCHAR(256) NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_document_chunk_chunk_id` (`chunk_id`),
  UNIQUE KEY `uk_document_chunk_qdrant_point_id` (`qdrant_point_id`),
  KEY `idx_document_chunk_document` (`document_id`),
  KEY `idx_document_chunk_tenant` (`tenant_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
